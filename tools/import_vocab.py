#!/usr/bin/env python3
"""Build data/vocab/<set-id>.js from plain-text word lists ("russian | french" per line).
Usage: python3 tools/import_vocab.py <set-id> list1.txt list2.txt ...   (files are concatenated in the given order)"""
import sys, pathlib
if len(sys.argv) < 3: sys.exit(__doc__)
sid, files = sys.argv[1], sys.argv[2:]
lines, skipped = [], 0
for f in files:
    for raw in pathlib.Path(f).read_text(encoding="utf-8-sig").splitlines():
        s = raw.strip()
        if not s: continue
        if "|" not in s: skipped += 1; print("skipped (no '|'):", s); continue
        ru, fr = (x.strip() for x in s.split("|", 1)); lines.append(f"{ru} | {fr}")
body = "\n".join(lines).replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
out = pathlib.Path(__file__).resolve().parent.parent / "data/vocab" / f"{sid}.js"
out.write_text(f'// Generated by tools/import_vocab.py — one "russian | french" pair per line. You can also edit it by hand.\nregisterVocab("{sid}", `\n{body}\n`);\n', encoding="utf-8")
print(f"{len(lines)} words written to {out.relative_to(out.parent.parent.parent)} ({skipped} skipped)")
